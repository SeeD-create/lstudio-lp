const state = { industry: null, index: 0, answers: [] };
const el = id => document.getElementById(id);

document.querySelectorAll(".industry-card").forEach(btn => {
  btn.addEventListener("click", () => start(btn.dataset.industry));
});
el("backBtn").addEventListener("click", goBack);
el("restartBtn").addEventListener("click", restart);

function show(id) {
  document.querySelectorAll(".screen").forEach(node => {
    const on = node.id === id;
    node.hidden = !on;
    node.classList.toggle("active", on);
  });
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function start(industry) {
  state.industry = industry;
  state.index = 0;
  state.answers = [];
  el("industryLabel").textContent = CONFIG[industry].label;
  show("quiz");
  renderQuestion();
}

function renderQuestion() {
  const cfg = CONFIG[state.industry];
  const item = cfg.questions[state.index];
  el("currentNum").textContent = String(state.index + 1);
  el("progressBar").style.width = `${(state.index + 1) * 10}%`;
  el("questionCategory").textContent = item.category.toUpperCase();
  el("question-title").textContent = item.title;
  el("questionHelp").textContent = item.help;
  const answers = el("answers");
  answers.replaceChildren();
  item.answers.forEach(answer => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "answer-btn";
    button.textContent = answer.label;
    button.addEventListener("click", () => chooseAnswer(answer.points));
    answers.append(button);
  });
  el("backBtn").textContent = state.index === 0 ? "← 業種選択" : "← 前の質問";
}

function chooseAnswer(points) {
  state.answers[state.index] = points;
  if (state.index < 9) {
    state.index += 1;
    renderQuestion();
  } else {
    renderResult();
  }
}

function goBack() {
  if (state.index === 0) { restart(); return; }
  state.index -= 1;
  renderQuestion();
}

function restart() {
  state.industry = null;
  state.index = 0;
  state.answers = [];
  show("intro");
}

function renderResult() {
  const cfg = CONFIG[state.industry];
  const categoryScores = {};
  let raw = 0;
  cfg.questions.forEach((question, index) => {
    const points = state.answers[index] || 0;
    raw += points;
    question.tags.forEach((tag, tagIndex) => {
      categoryScores[tag] = (categoryScores[tag] || 0) + points * (tagIndex === 0 ? 1 : .65);
    });
  });
  const score = Math.min(100, Math.round(raw));
  const top = Object.entries(categoryScores).sort((a,b) => b[1] - a[1]).slice(0,3).map(([tag]) => tag);

  el("resultIndustry").textContent = `${cfg.label}向け診断結果`;
  el("resultHeadline").replaceChildren(...cfg.headline.map(line => {
    const span = document.createElement("span");
    span.textContent = line;
    return span;
  }));
  el("resultSummary").textContent = resultSummary(score, cfg.label);
  el("scoreValue").textContent = String(score);
  el("scoreLabel").textContent = scoreLabel(score);
  requestAnimationFrame(() => { el("scoreBar").style.width = `${score}%`; });

  const recWrap = el("recommendations");
  recWrap.replaceChildren();
  top.forEach((tag, index) => {
    const item = cfg.recommendations[tag];
    const card = document.createElement("article");
    card.className = "rec-card";
    card.innerHTML = `<span class="rec-rank">PRIORITY 0${index + 1}</span><h3></h3><p></p><dl><dt>使う仕組み</dt><dd></dd><dt>目指す変化</dt><dd></dd></dl>`;
    card.querySelector("h3").textContent = item.title;
    card.querySelector("p").textContent = item.description;
    const dds = card.querySelectorAll("dd");
    dds[0].textContent = item.tools; dds[1].textContent = item.outcome;
    recWrap.append(card);
  });

  const future = el("futureGrid");
  future.replaceChildren();
  cfg.future.forEach(([title,text]) => future.append(makeCard("future-item", title, text)));
  const agents = el("agentExamples");
  agents.replaceChildren();
  cfg.agents.forEach(([title,text]) => agents.append(makeCard("agent-card", title, text)));
  show("result");
}

function makeCard(className, title, text) {
  const card = document.createElement("article");
  card.className = className;
  const strong = document.createElement("b");
  const p = document.createElement("p");
  strong.textContent = title; p.textContent = text;
  card.append(strong,p);
  return card;
}

function scoreLabel(score) {
  if (score >= 75) return "改善候補が多く、優先順位を決めれば効果を出しやすい状態です。";
  if (score >= 50) return "小さな改善から始め、30日単位で業務へ定着させやすい状態です。";
  if (score >= 25) return "対象を一つに絞り、無理なく試すことから始める段階です。";
  return "AI導入を急がず、現在の手順を整えることが先です。";
}

function resultSummary(score, label) {
  if (score >= 75) return `${label}の業務には、AIと自動化を使える候補が複数あります。一度に全部変えず、受付・文書・転記のうち効果が見えやすい一つから始めるのが適切です。`;
  if (score >= 50) return `${label}の業務では、部分的なAI活用が有効です。毎月一つずつ仕組みを整えれば、現場の負担を増やさず定着させられます。`;
  if (score >= 25) return `${label}の業務では、限定した作業から試すのが適切です。文章の下書きや通知など、失敗しても影響が小さい部分から始めます。`;
  return `${label}では、現在の作業手順を見える化することが最初の一手です。AIを入れること自体を目的にせず、繰り返し作業が見つかってから導入します。`;
}
