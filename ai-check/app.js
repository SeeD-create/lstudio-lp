function makeIndustry({ label, headline, items, future, agents }) {
  const recommendations = {};
  const questions = items.map(item => {
    const [key, category, title, help, recTitle, description, tools, outcome, answerType = "condition"] = item;
    recommendations[key] = rec(recTitle, description, tools, outcome);
    return q(category, title, help, answerType, [key]);
  });
  return { label, headline, questions, recommendations, future, agents };
}

